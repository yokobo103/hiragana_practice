// ずかんのページ名（5字ずつの区切りに対応）
const PAGE_TITLES = {
  hira: {
    seion:  ["あ行","か行","さ行","た行","な行","は行","ま行","や行","ら行","わ行"],
    dakuon: ["が行","ざ行","だ行","ば行","ぱ行"],
    small:  ["ちいさいじ 1","ちいさいじ 2"]
  },
  kata: {
    seion:  ["ア行","カ行","サ行","タ行","ナ行","ハ行","マ行","ヤ行","ラ行","ワ行"],
    dakuon: ["ガ行","ザ行","ダ行","バ行","パ行"],
    small:  ["ちいさいじ 1","ちいさいじ 2","のばすぼう"]
  }
};

/** ずかんのページ一覧を作る。1ページ = 五十音の1行。
 *  はみ出して1字だけになるページは前のページに混ぜる
 *  （1字で「ページかんせい！」が出るとご褒美が安くなるため）。 */
export function pagesOf(kana){
  const out = [];
  for (const set of ["seion","dakuon","small"]){
    const list = SETS[kana][set];
    const titles = PAGE_TITLES[kana][set];
    const pages = [];
    for (let i = 0; i < list.length; i += 5){
      const chars = list.slice(i, i+5).filter(Boolean);
      if (!chars.length) continue;
      pages.push({ set, title: titles[i/5] || "", chars });
    }
    if (pages.length > 1 && pages[pages.length-1].chars.length === 1){
      const tail = pages.pop();
      pages[pages.length-1].chars.push(...tail.chars);
    }
    out.push(...pages);
  }
  return out;
}

/** その字が どっちのかなか */
export function kanaOf(ch){
  const c = ch.codePointAt(0);
  return (c >= 0x30a1 && c <= 0x30fc) ? "kata" : "hira";
}

export function readingOf(ch){
  const w = WORDS[ch];
  if (!w) return ch;
  if (w.say) return w.say;
  return `${ch}、${w.w}の ${ch}`;
}
